import { build } from 'vite'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const result = await build({ configFile: false, logLevel: 'error', build: {
  write: false, minify: false, target: 'es2020',
  lib: { entry: fileURLToPath(new URL('src/lib/clientPeriodMailer.js', root)), name: 'ClientPeriodMailCore', formats: ['iife'] },
} })
const code = (Array.isArray(result) ? result : [result]).flatMap((bundle) => bundle.output).find((item) => item.type === 'chunk').code
const runtime = await readFile(new URL('scripts/client-period-mailer-runtime.gs', root), 'utf8')
const logo = await readFile(new URL('scripts/assets/client-period-mail-logo.jpg', root))
if (logo.length > 50000) throw new Error('Default mail logo must be smaller than 50 KB.')
const defaultLogo = 'var CLIENT_PERIOD_DEFAULT_LOGO = ' + JSON.stringify('data:image/jpeg;base64,' + logo.toString('base64')) + ';\n'
await writeFile(new URL('scripts/client-period-mailer-appscript.gs', root),
  '// Complete EV91 Client Period Trend mailer. Paste the ENTIRE file into a separate Apps Script project.\n// Generated by npm run prepare:client-period-mailer.\n' + code + '\n' + defaultLogo + runtime)
console.log('Prepared scripts/client-period-mailer-appscript.gs')
