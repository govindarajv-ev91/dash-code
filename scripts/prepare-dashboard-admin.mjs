import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const entry = await readFile(new URL('supabase/functions/dashboard-admin/index.ts', root), 'utf8')
const handler = await readFile(new URL('supabase/functions/dashboard-admin/handler.js', root), 'utf8')
// The shared handler stays JavaScript for Node tests; the editor bundle needs
// explicit TypeScript annotations because JSDoc does not type TS parameters.
let typedHandler = handler
for (const [source, typed] of [
  ['function reply(status, body)', 'function reply(status: number, body: unknown)'],
  ['function createAdminHandler(client)', "function createAdminHandler(client: import('npm:@supabase/supabase-js@2.102.1').SupabaseClient)"],
  ['return async (request) =>', 'return async (request: Request) =>'],
]) {
  if (!typedHandler.includes(source)) throw new Error(`Admin handler changed; update the editor bundle generator: ${source}`)
  typedHandler = typedHandler.replace(source, typed)
}
const startup = entry.slice(entry.indexOf('const client ='))
if (!startup.includes('Deno.serve(createAdminHandler(client))')) throw new Error('Admin entry point changed; update the editor bundle generator.')
const content = [
  '// Generated by npm run prepare:admin from the tested admin handler.\n// Paste this entire file into the Supabase Edge Function editor; name the function dashboard-admin.\n// Set Verify JWT OFF; this handler verifies the token with Auth and checks the admin role itself.',
  entry.split(/\r?\n/)[0], typedHandler, startup,
].join('\n\n')
await writeFile(new URL('supabase/dashboard-admin-editor.ts', root), content)
console.log('Prepared supabase/dashboard-admin-editor.ts for Supabase Dashboard > Edge Functions > Deploy a new function > Via Editor.')
