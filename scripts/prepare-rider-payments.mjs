import { mkdir, readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const target = new URL('supabase/functions/rider-payments/', root)
await mkdir(new URL('lib/', target), { recursive: true })
const source = await readFile(new URL('api/rider-payments.js', root), 'utf8')
// Keep the deployed handler identical to the Node-tested handler, with the
// database client and secrets supplied by the Edge Function entry point.
const handler = source
  .replace("import { getSupabase } from './lib/supabaseServer.js'", '')
  .replace('getClient = getSupabase', 'getClient')
  .replace('export default createRiderPaymentsHandler()', '')
if (handler === source || handler.includes('getSupabase')) throw new Error('Update the payment function generator for the changed handler.')
await writeFile(new URL('handler.js', target), '// Generated by npm run prepare:rider-payments. Edit api/rider-payments.js.\n' + handler)
await writeFile(new URL('lib/riderPaymentFeed.js', target),
  '// Generated by npm run prepare:rider-payments. Edit api/lib/riderPaymentFeed.js.\n' +
  await readFile(new URL('api/lib/riderPaymentFeed.js', root), 'utf8'))
console.log('Prepared the rider-payments Edge Function from the tested API sources.')
