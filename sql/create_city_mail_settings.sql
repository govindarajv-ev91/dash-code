-- Run in Supabase SQL Editor after sql/create_dashboard_auth.sql.
-- Contacts, schedules and delivery logs are private to dashboard administrators.
begin;
create or replace function public.city_mail_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.dashboard_users where id = (select auth.uid()) and role = 'admin');
$$;
revoke all on function public.city_mail_is_admin() from public, anon;
grant execute on function public.city_mail_is_admin() to authenticated;

create or replace function public.city_mail_valid_emails(value text, required boolean)
returns boolean language sql immutable set search_path = '' as $$
  select length(value) <= 4000 and
    case when btrim(value) = '' then not required else
      (select count(*) <= 40 and bool_and(btrim(email) ~ '^[^[:space:]@,<>]+@[^[:space:]@,<>]+\.[^[:space:]@,<>]+$')
       from unnest(string_to_array(value, ',')) as email) end;
$$;

create table if not exists public.city_mail_contacts (
  id bigint generated by default as identity primary key,
  city text not null check (btrim(city) <> '' and city not in ('All', 'Unknown') and length(city) <= 80),
  name text not null check (btrim(name) <> '' and length(name) <= 200),
  email_id text not null check (public.city_mail_valid_emails(email_id, true)),
  phone_number text not null default '' check (length(phone_number) <= 80),
  cc text not null default '' check (public.city_mail_valid_emails(cc, false)),
  created_at timestamptz not null default now()
);
create unique index if not exists city_mail_contact_city on public.city_mail_contacts (lower(btrim(city)));

create table if not exists public.client_period_mail_schedules (
  id bigint generated by default as identity primary key,
  contact_id bigint not null references public.city_mail_contacts(id),
  day_of_week integer check (day_of_week between 0 and 6), -- NULL = daily; 0 = Sunday
  send_time time not null check (extract(second from send_time) = 0), -- Asia/Kolkata
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists city_mail_schedule_slot on public.client_period_mail_schedules (contact_id, coalesce(day_of_week, -1), send_time);
create or replace function public.city_mail_touch_schedule()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;
drop trigger if exists city_mail_schedule_updated on public.client_period_mail_schedules;
create trigger city_mail_schedule_updated before update on public.client_period_mail_schedules
for each row execute function public.city_mail_touch_schedule();

create table if not exists public.client_period_mail_runs (
  id bigint generated by default as identity primary key,
  schedule_id bigint not null references public.client_period_mail_schedules(id),
  run_date date not null,
  status text not null check (status in ('preparing', 'sending', 'sent', 'failed', 'uncertain')),
  message text not null default '',
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  unique(schedule_id, run_date)
);

do $$
declare tbl text;
begin
  foreach tbl in array array['city_mail_contacts', 'client_period_mail_schedules', 'client_period_mail_runs'] loop
    execute format('alter table public.%I enable row level security', tbl);
    execute format('revoke all on public.%I from public, anon, authenticated', tbl);
    execute format('grant select on public.%I to authenticated', tbl);
    execute format('grant all on public.%I to service_role', tbl);
    execute format('grant usage, select on sequence public.%I to service_role', tbl || '_id_seq');
    execute format('drop policy if exists admin_read on public.%I', tbl);
    execute format('create policy admin_read on public.%I for select to authenticated using ((select public.city_mail_is_admin()))', tbl);
    if tbl <> 'client_period_mail_runs' then
      execute format('grant insert, update on public.%I to authenticated', tbl);
      execute format('grant usage on sequence public.%I to authenticated', tbl || '_id_seq');
      execute format('drop policy if exists admin_insert on public.%I', tbl);
      execute format('drop policy if exists admin_update on public.%I', tbl);
      execute format('create policy admin_insert on public.%I for insert to authenticated with check ((select public.city_mail_is_admin()))', tbl);
      execute format('create policy admin_update on public.%I for update to authenticated using ((select public.city_mail_is_admin())) with check ((select public.city_mail_is_admin()))', tbl);
    end if;
  end loop;
end $$;
notify pgrst, 'reload schema';
commit;
